async def _collect(gen: AsyncIterator[dict]) -> list[dict]:
    """Drain an async generator into a list."""
    out: list[dict] = []
    async for ev in gen:
        out.append(ev)
    return out


def _is_uuid_like(value: Any) -> bool:
    """True iff `value` looks like a UUID hex or `prop_<hex>` id we mint
    in `propose_transaction` and `slip_handler`."""
    if not isinstance(value, str) or not value:
        return False
    if value.startswith("prop_"):
        return bool(re.fullmatch(r"prop_[0-9a-f]+", value))
    # Bare hex (group_id, sync_id, transaction.sync_id) — UUID4-no-dashes
    # is 32 hex chars; full UUID with dashes is 36; either is fine.
    return bool(re.fullmatch(r"[0-9a-f]{32}|[0-9a-f-]{36}", value))


def _assert_v2_event_shape(events: list[dict]) -> None:
    """Every event is `{"event": str, "data": str}` with event ∈ V2 names."""
    for ev in events:
        assert isinstance(ev, dict), f"non-dict event leaked: {ev!r}"
        assert set(ev.keys()) == {"event", "data"}, (
            f"wrong event shape — must be {{event,data}}, got {sorted(ev.keys())}"
        )
        assert isinstance(ev["event"], str)
        assert isinstance(ev["data"], str)
        assert ev["event"] in V2_EVENT_NAMES, (
            f"unknown event name {ev['event']!r} — mobile decoder won't route it"
        )


def _decode_blocks(events: list[dict]) -> list[dict]:
    """Extract + JSON-decode every `event: block` payload."""
    out: list[dict] = []
    for ev in events:
        if ev["event"] == "block":
            out.append(json.loads(ev["data"]))
    return out


def _assert_snake_case_only(events: list[dict]) -> None:
    """Guard against accidental camelCase in any block payload.

    Mobile decoder reads snake_case keys (`proposal_id`, `wallet_sync_id`,
    `option_kind`). A v3 emitter that ships `proposalId` instead causes a
    silent decoder drop — the most common production bug per spec §8.
    """
    BAD_CAMEL = (
        "proposalId",
        "walletSyncId",
        "categorySyncId",
        "optionKind",
        "syncId",
        "groupId",
        "currencyCode",
        "threadId",
        "stt_error".upper(),
    )
    for ev in events:
        if ev["event"] != "block":
            continue
        raw = ev["data"]
        for bad in BAD_CAMEL:
            assert bad not in raw, (
                f"camelCase key {bad!r} leaked into block payload — "
                f"mobile decoder reads snake_case only"
            )


def _assert_thai_pass_through(events: list[dict]) -> None:
    """Status / answer tokens MUST be raw UTF-8 Thai, not \\uXXXX escapes."""
    for ev in events:
        if ev["event"] not in {"status_token", "answer_token"}:
            continue
        # \u0E is the Thai Unicode block prefix — its escape form is the
        # silent failure: mobile shows literal "\\u0e2a" instead of Thai
        # glyphs. ensure_ascii=False on the server side avoids this; assert
        # to catch a regression that flipped it.
        assert "\\u0e" not in ev["data"].lower(), (
            f"Thai escape sequence leaked into {ev['event']!r}: {ev['data']!r}"
        )


