@pytest.mark.xfail(reason=_FAKE_ASTREAM_GAP_REASON, strict=True)
def test_UT_MC01_text_add_wire_matches_v2_contract() -> None:
    """UT-MC01: text ADD turn yields the v2 sequence — status_token(s)
    before the transaction_proposal, then a final block:answer + done.

    Sequence per spec §10.1:
      [status_token]* → block:transaction_proposal → answer_token* →
      block:answer → done
    """
    _install_test_catalog()

    # Two-step ReAct: (1) call get_user_context, (2) call propose_transaction,
    # (3) compose final answer (no more tool_calls).
    fake = FakeToolingModel(
        responses=[
            _ai_tool_call("get_user_context", {}, "c1"),
            _ai_tool_call(
                "propose_transaction",
                {
                    "amount": 250.0,
                    "type": "expense",
                    "category_label": "กาแฟ",
                    "note": "กาแฟ",
                },
                "c2",
            ),
            AIMessage(content="บันทึก 250 บาท หมวดกาแฟแล้วครับ"),
        ]
    )

    async def _run() -> list[dict]:
        graph = await build_graph(
            model=fake,
            checkpointer=MemorySaver(),
        )
        from src.agent.streaming.sse_adapter import stream_chat

        init_state: dict = {
            "user_id": "u-mc01",
            "thread_id": "t-mc01",
            "messages": [HumanMessage(content="เพิ่ม 250 กาแฟ")],
            "user_context": None,
            "tool_outputs_this_turn": [],
            "emitted_blocks_this_turn": [],
        }
        config: dict = {
            "configurable": {"thread_id": "t-mc01"},
            "recursion_limit": 25,
        }
        return await _collect(
            stream_chat(graph, init_state, config, thread_id="t-mc01")
        )

    events = asyncio.run(_run())
    _assert_v2_event_shape(events)
    _assert_snake_case_only(events)
    _assert_thai_pass_through(events)

    # Terminal: `done` carrying thread_id.
    assert events[-1]["event"] == "done"
    assert json.loads(events[-1]["data"]) == {"thread_id": "t-mc01"}

    # Status tokens — at least the two tools (get_user_context, propose)
    # each emit one.
    status_tokens = [e for e in events if e["event"] == "status_token"]
    assert len(status_tokens) >= 2, (
        f"expected ≥2 status_tokens (one per tool), got {len(status_tokens)}"
    )
    status_data = {e["data"] for e in status_tokens}
    assert "กำลังเช็คข้อมูล..." in status_data
    assert "กำลังบันทึก..." in status_data

    # Block events — must include transaction_proposal + answer.
    blocks = _decode_blocks(events)
    block_types = [b["type"] for b in blocks]
    assert "transaction_proposal" in block_types
    assert "answer" in block_types
    # transaction_proposal MUST come BEFORE block:answer (mobile UX order).
    proposal_idx = block_types.index("transaction_proposal")
    answer_idx = block_types.index("answer")
    assert proposal_idx < answer_idx, "answer must follow proposal block"

    # Proposal shape — UUID placeholders, snake_case, validates.
    proposal = blocks[proposal_idx]
    assert validate_block(proposal)
    assert _is_uuid_like(proposal["proposal_id"])
    txn = proposal["transaction"]
    assert txn["amount"] == 250
    assert txn["type"] == "expense"
    assert "wallet_sync_id" in txn
    assert "sync_id" in txn


