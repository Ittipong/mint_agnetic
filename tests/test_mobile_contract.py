# 3. FakeToolingModel — deterministic ReAct loop driver
# ---------------------------------------------------------------------------


class FakeToolingModel(BaseChatModel):
    """Deterministic chat model for end-to-end SSE tests.

    Pops one canned AIMessage per `_generate` call. `bind_tools` is a no-op
    so `create_react_agent`'s binding step doesn't crash on a fake.

    NOTE: this fake DOES NOT stream — astream returns the same AIMessage
    as a single AIMessageChunk so `_yield_message_event` still produces
    `answer_token` events. Real production streaming yields multiple
    chunks per message; the assertion surface here is "at least one
    answer_token + the final block:answer", not exact chunk counts.
    """

    responses: list = []
    cursor: int = 0

    @property
    def _llm_type(self) -> str:
        return "fake_mobile_contract"

    def _generate(self, messages, stop=None, **kwargs):  # type: ignore[no-untyped-def]
        idx = self.cursor
        if idx >= len(self.responses):
            # Loop runaway guard — replay last with no tool_calls so the
            # ReAct loop exits cleanly.
            msg = AIMessage(content="end")
        else:
            msg = self.responses[idx]
        # Mutating class state on the instance is fine here because each
        # test instantiates a fresh model.
        object.__setattr__(self, "cursor", idx + 1)
        return ChatResult(generations=[ChatGeneration(message=msg)])

    async def _agenerate(self, messages, stop=None, **kwargs):  # type: ignore[no-untyped-def]
        return self._generate(messages, stop=stop, **kwargs)

    def bind_tools(self, tools, **kwargs):  # type: ignore[no-untyped-def]
        return self


def _ai_tool_call(name: str, args: dict, call_id: str) -> AIMessage:
    """Build an AIMessage that triggers exactly one tool call in the ReAct loop."""
    return AIMessage(
        content="",
        tool_calls=[{"name": name, "args": args, "id": call_id, "type": "tool_call"}],
    )


