# Known issue: sse_adapter __RESET__ sentinel leak (flagged for Phase 4)
# ---------------------------------------------------------------------------
#
# When the v3 graph runs, the pre_turn_hook writes `["__RESET__"]` to the
# `emitted_blocks_this_turn` channel — `append_reducer` (state.py L101+)
# translates that sentinel to `[]` at the reducer level. BUT LangGraph's
# `stream_mode="updates"` stream forwards the RAW write (`["__RESET__"]`),
# not the reduced value.
#
# `streaming/sse_adapter.py::stream_chat` then sees `new_blocks =
# ["__RESET__"]`, treats each entry as a block dict, calls `validate_block`
# (returns False), and falls into the diagnostic slog string:
#     f"...type={(blk or {}).get('type')!r} keys={list((blk or {}).keys())}"
# `blk` is the string "__RESET__" — `str.get` does not exist →
# AttributeError → caught by the outer except → `event: error` reaches the
# wire INSTEAD of any block.
#
# Root cause is one line in sse_adapter (filter `__RESET__` strings out of
# `new_blocks` BEFORE the validate loop). Wave 7a scope explicitly forbids
# `src/` edits, so the affected graph-driven tests below are marked xfail
# with strict=True. Phase 4 reviewer should:
#   1) Patch sse_adapter to filter `__RESET__` and re-emit nothing for that
#      sentinel.
#   2) Remove these xfail markers.
#   3) Re-run UT-MC01..MC04 — they assert the correct wire contract.
#
# This is exactly the "silent wire breakage" risk R3 the Wave 7 mobile-
# contract tests are designed to surface. We surface it as a strict xfail
# so it can't be accidentally hidden by a future fix.
_RESET_LEAK_XFAIL_REASON = (
    "[RESOLVED Wave 7 final] sse_adapter now filters `__RESET__` sentinels. "
    "2/7 originally-xfailed tests now pass. Remaining 5 deferred to "
    "FakeToolingModel _astream gap (see _FAKE_ASTREAM_GAP_REASON)."
)
# 5 graph-driven tests below still fail because `FakeToolingModel` only
# implements `_generate`/`_agenerate`, NOT `_astream`. LangGraph's
# `astream(stream_mode="messages")` needs the model to support streaming
# to produce `AIMessageChunk` events. Without those, `answer_chunks`
# stays empty → no `block:answer` at end-of-graph.
#
# This is a TEST INFRASTRUCTURE gap, not a production bug. The wire
