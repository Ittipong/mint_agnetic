"""Golden SSE wire diff: v3 output vs frozen v2 mobile-facing contract.

Covers UT-MC01..UT-MC04 — the most critical Wave 7 test surface.

Goal:
  For 4 representative traces (text ADD, voice ADD, slip, advisor), drive
  the v3 streaming surface and assert the emitted SSE event sequence
  matches the v2 contract the frozen mobile decoder reads.

What "matches" means here (tolerances):
  - Event NAMES must be exactly the v2 set
    ({status_token, answer_token, block, done, error}).
  - Event ORDER per trace must follow the spec §10 sequence diagram.
  - `block` payloads must be JSON dicts whose keys are snake_case and
    whose `type` is in `EMITTABLE_BLOCK_TYPES`.
  - `block:transaction_proposal` / `block:transcript` / `block:answer`
    must decode through `block_emitter.validate_block` AND match the
    structural shape mobile's `decodeBlockJson` reads.
  - UUID-ish keys (`proposal_id`, `group_id`, `transaction.sync_id`,
    `thread_id`) are placeholder-matched — they vary per turn by design.
  - `event: status_token` / `event: answer_token` data is raw text and
    must NOT contain Unicode escape sequences (Thai pass-through).

What's deliberately NOT byte-for-byte:
  - The trailing `block:answer` text is generated by the model; we assert
    its presence + shape, not exact wording.
  - For advisor (UT-MC04) the number of `status_token`s depends on how
    many tools fire; we assert a non-empty subset and the terminal
    `block:answer` + `done`.

Mocking strategy:
  - Text ADD + Advisor: a `FakeToolingModel` (lifted from test_react_loop
    pattern) drives `build_graph()` with a scripted tool-call sequence.
  - Voice + Slip: drive `handle_voice_chat` / `handle_slip_chat` directly
    with mocked STT / vision callables (no real OpenRouter).

Spec sources:
  - Wire shape: `streaming/sse_adapter.py` + `streaming/block_emitter.py`
  - Sequence diagrams: `docs/mint_agentic_v3_pure_react_spec.html` §10
  - Mobile decoder ground truth:
    `mobile/lib/data/datasources/remote/api/chat_api_datasource.dart`
    `_decodeSegment` (~761-794) + `decodeBlockJson` (~859-1018)

Phase 4 review flag:
  These golden assertions describe today's shapes — when block_emitter
  schemas grow new keys, update the assertions in lockstep. The Wave 5
  block_emitter validators are the regression backstop; this test only
  asserts the wire shape mobile consumes.
"""

